/** Translate a key, filling {placeholders}. Falls back to English, then to the key. */
export function t(key, params) {
  // Singular variant ("…_one") when the count is exactly 1.
  if (params && String(params.n) === '1' && (STRINGS[currentLang][`${key}_one`] ?? STRINGS.en[`${key}_one`])) key = `${key}_one`;
  const s = STRINGS[currentLang][key] ?? STRINGS.en[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
}
