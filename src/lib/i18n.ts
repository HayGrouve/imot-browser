type Strings = typeof STRINGS.en
export type StringKey = keyof Strings | (string & {})
export type Params = Record<
  string,
  string | number | boolean | null | undefined
>

/** Translate a key, filling {placeholders}. Falls back to English, then to the key. */
export function translate(lang: Lang, key: StringKey, params?: Params): string {
  const table = STRINGS[lang] as Record<string, string | undefined>
  const en = STRINGS.en as Record<string, string | undefined>
  let k = key
  // Singular variant ("…_one") when the count is exactly 1.
  if (
    params &&
    String(params.n) === '1' &&
    (table[`${k}_one`] ?? en[`${k}_one`])
  )
    k = `${k}_one`
  const s = table[k] ?? en[k] ?? k
  if (!params) return s
  return s.replace(/\{(\w+)\}/g, (m, p: string) => {
    const v = params[p]
    return v == null ? m : String(v)
  })
}
